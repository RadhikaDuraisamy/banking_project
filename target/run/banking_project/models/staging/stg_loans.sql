
  create or replace   view BANKING_DW.DBT_DEV.stg_loans
  
  
  
  
  as (
    SELECT
    LOAN_ID,
    CUSTOMER_ID,
    UPPER(TRIM(LOAN_TYPE)) AS LOAN_TYPE,
    PRINCIPAL_AMOUNT,
    INTEREST_RATE,
    DISBURSEMENT_DATE,
    UPPER(TRIM(LOAN_STATUS)) AS LOAN_STATUS,
    MONTHLY_EMI,
    TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT
FROM BANKING_DW.RAW.LOANS
  );

