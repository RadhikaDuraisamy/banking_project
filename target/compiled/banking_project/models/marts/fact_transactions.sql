
select
  TRANSACTION_ID,
    ACCOUNT_ID,
    TRANSACTION_TIMESTAMP,
    TRANSACTION_TYPE,
    TRANSACTION_CHANNEL,
    AMOUNT,
TRANSACTION_STATUS,
   UPDATED_AT
FROM BANKING_DW.DBT_DEV.stg_transactions

 
where UPDATED_AT>=
(select coalesce(max(UPDATED_AT),'1900-01-01'::timestamp) from BANKING_DW.DBT_DEV.fact_transactions )
